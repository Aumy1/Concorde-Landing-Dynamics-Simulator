function validateConfig(p)
%VALIDATECONFIG Reject incomplete, misspelled, nonfinite or unsupported inputs.
% Bounds define this project's computational envelope, not aircraft limits.
base = landing.defaultConfig();
isA350 = isfield(p,'visual');
if isA350
    assert(isstruct(p.visual) && strcmp(p.visual.aircraft,'A350') && ...
        isnumeric(p.visual.alpha) && isscalar(p.visual.alpha) && isfinite(p.visual.alpha), ...
        'landing:InvalidConfig','Invalid A350 visual configuration.');
    p = rmfield(p,'visual');
end
groups = fieldnames(base);
assert(isstruct(p) && isscalar(p), 'landing:InvalidConfig', ...
    'Configuration must be a scalar structure.');
assert(isequal(sort(fieldnames(p)), sort(groups)), ...
    'landing:InvalidConfig', 'Unexpected or missing configuration groups.');
for i = 1:numel(groups)
    group = groups{i}; names = fieldnames(base.(group));
    assert(isstruct(p.(group)) && isscalar(p.(group)) && ...
        isequal(sort(fieldnames(p.(group))), sort(names)), ...
        'landing:InvalidConfig', 'Unexpected/missing fields in %s.', group);
    for j = 1:numel(names)
        value = p.(group).(names{j});
        assert(isnumeric(value) && isreal(value) && isscalar(value) && ...
            isfinite(value), 'landing:InvalidConfig', ...
            '%s.%s must be a finite real numeric scalar.', group, names{j});
        if ~strcmp(group, 'environment') || ~strcmp(names{j}, 'wind')
            assert(value >= 0, 'landing:InvalidConfig', ...
                '%s.%s cannot be negative.', group, names{j});
        end
    end
end
positive = [p.aircraft.mass p.aircraft.wingArea p.aircraft.clMax ...
    p.aircraft.maxThrust p.environment.rho p.environment.g ...
    p.flare.height p.flare.sinkTarget p.control.pathTimeConstant ...
    p.control.speedTimeConstant p.ground.brakeRamp p.ground.reverseRamp ...
    p.ground.liftDecayTime p.ground.reverseFadeSpeed p.runway.length ...
    p.solver.relativeTolerance p.solver.absoluteTolerance p.solver.maxStep ...
    p.solver.maxAirTime p.solver.maxGroundTime];
assert(all(positive > 0), 'landing:InvalidConfig', ...
    'Physical scales, time constants, ramps and solver settings must be positive.');
massOK = p.aircraft.mass >= 80000 && p.aircraft.mass <= 120000;
if isA350, massOK = p.aircraft.mass >= 150000 && p.aircraft.mass <= 220000; end
assert(massOK && ...
    p.environment.rho >= 0.9 && p.environment.rho <= 1.4 && ...
    abs(p.environment.wind) <= 15 && p.approach.speed >= 75 && ...
    p.approach.speed <= 100 && p.flare.speed >= 70 && ...
    p.flare.speed <= p.approach.speed && p.approach.glideAngle >= deg2rad(2) && ...
    p.approach.glideAngle <= deg2rad(4) && p.flare.height <= 25 && ...
    p.approach.initialHeight > p.approach.thresholdHeight && ...
    p.approach.thresholdHeight > p.flare.height && ...
    p.flare.sinkTarget < p.approach.speed*sin(p.approach.glideAngle) && ...
    p.ground.brakeMu <= 0.6 && p.ground.rollingMu <= 0.1 && ...
    p.ground.residualCL <= p.aircraft.clMax && ...
    p.solver.relativeTolerance <= 1e-3 && p.solver.maxStep <= 1, ...
    'landing:InvalidConfig', 'Configuration exceeds the documented model envelope.');
end
