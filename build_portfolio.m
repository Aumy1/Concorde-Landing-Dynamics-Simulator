function build_portfolio()
%BUILD_PORTFOLIO Reproduce tests, data, plots and measured validation report.
root = fileparts(mfilename('fullpath')); addpath(root);
results = run_tests();
r = run_demo(fullfile(root,'results','baseline'),false);
run_scenarios(fullfile(root,'results','scenarios'),false);
p = r.config; p.solver.maxStep = .05;
p.solver.relativeTolerance = 1e-10; p.solver.absoluteTolerance = 1e-11;
fine = landing.simulate(p);
path = fullfile(root,'docs','VALIDATION.md');
fid = fopen(path,'w'); assert(fid >= 0,'landing:FileWrite','Cannot write report.');
cleanup = onCleanup(@() fclose(fid));
fprintf(fid,'# Measured validation report\n\n');
fprintf(fid,'Generated by `build_portfolio` using MATLAB %s (%s), %s.\n\n', ...
    version,computer,char(datetime('now','TimeZone','America/Toronto','Format','yyyy-MM-dd HH:mm:ss z')));
fprintf(fid,'**%d / %d tests passed; %d incomplete.** See `results/verification/tests.csv` and `junit.xml`.\n\n', ...
    sum([results.Passed]),numel(results),sum([results.Incomplete]));
fprintf(fid,'## Baseline\n\nMetric | Result\n--- | ---\n');
m = r.metrics;
fprintf(fid,'Touchdown airspeed | %.3f m/s (%.2f kt)\n',m.touchdownAirspeed_mps,m.touchdownAirspeed_kt);
fprintf(fid,'Touchdown sink rate | %.4f m/s downward\n',m.touchdownSinkRate_mps);
fprintf(fid,'Touchdown coordinate | %.3f m from threshold\n',m.touchdownX_m);
fprintf(fid,'Ground roll | %.3f m\nStop coordinate | %.3f m\n',m.groundRoll_m,m.stopX_m);
fprintf(fid,'Ground roll time | %.3f s\nRemaining runway | %.3f m\n',m.groundRollTime_s,m.runwayRemaining_m);
fprintf(fid,'Any sampled control saturation | %s\n\n',mat2str(m.anyControlSaturation));
fprintf(fid,'## Numerical refinement\n\n');
fprintf(fid,'Baseline: RelTol 1e-8, AbsTol 1e-9, MaxStep 0.1 s. Refined: 1e-10, 1e-11, 0.05 s.\n\n');
fprintf(fid,'Metric | Absolute difference | Acceptance\n--- | --- | ---\n');
fprintf(fid,'Touchdown time | %.8g s | < 0.002 s\n',abs(fine.metrics.touchdownTime_s-m.touchdownTime_s));
fprintf(fid,'Touchdown sink | %.8g m/s | < 0.002 m/s\n',abs(fine.metrics.touchdownSinkRate_mps-m.touchdownSinkRate_mps));
fprintf(fid,'Ground roll | %.8g m | < 0.1 m\n\n',abs(fine.metrics.groundRoll_m-m.groundRoll_m));
fprintf(fid,'## Interpretation\n\n');
fprintf(fid,['Tests verify equations, event handling, an analytical constant-deceleration limit, ' ...
    'energy/work consistency, convergence, configuration rejection, exports and sensitivity trends. ' ...
    'They do not establish agreement with Concorde flight-test data. ' ...
    'The included CI workflow is configured but a hosted GitHub run is not implied by this local report.\n']);
fprintf('Portfolio build complete: %s\n',root);
end
